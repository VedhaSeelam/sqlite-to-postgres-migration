-- TARGET schema (PostgreSQL). The "new infrastructure".
-- Stricter than the source: real DATE/TIMESTAMP, NUMERIC(10,2) for money,
-- CHECK constraints, and identity columns instead of SQLite's rowid.
CREATE TABLE organiser (
    organiser_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    email        VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE venue (
    venue_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL,
    suburb   VARCHAR(60)  NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);
CREATE TABLE category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE customer (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(60)  NOT NULL,
    last_name   VARCHAR(60)  NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE event (
    event_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150) NOT NULL,
    organiser_id INTEGER NOT NULL REFERENCES organiser(organiser_id),
    venue_id     INTEGER NOT NULL REFERENCES venue(venue_id),
    category_id  INTEGER NOT NULL REFERENCES category(category_id),
    event_date   DATE NOT NULL,
    base_price   NUMERIC(10,2) NOT NULL CHECK (base_price >= 0)
);
CREATE TABLE ticket_type (
    ticket_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       INTEGER NOT NULL REFERENCES event(event_id),
    name           VARCHAR(60) NOT NULL,
    price          NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    quota          INTEGER NOT NULL CHECK (quota > 0)
);
CREATE TABLE booking (
    booking_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    INTEGER NOT NULL REFERENCES customer(customer_id),
    event_id       INTEGER NOT NULL REFERENCES event(event_id),
    ticket_type_id INTEGER NOT NULL REFERENCES ticket_type(ticket_type_id),
    quantity       INTEGER NOT NULL CHECK (quantity > 0),
    booking_date   TIMESTAMP NOT NULL,
    status         VARCHAR(20) NOT NULL CHECK (status IN ('confirmed','pending','cancelled'))
);
CREATE TABLE payment (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES booking(booking_id),
    amount     NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    method     VARCHAR(20) NOT NULL CHECK (method IN ('card','paypal','bank_transfer')),
    paid_at    TIMESTAMP NOT NULL,
    status     VARCHAR(20) NOT NULL CHECK (status IN ('paid','refunded','failed'))
);
